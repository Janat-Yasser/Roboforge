/** Small helpers for readable, deterministic code emission. */

export class CodeWriter {
  private readonly lines: string[] = [];
  private depth = 0;

  constructor(private readonly indentUnit = "  ") {}

  line(text = ""): this {
    this.lines.push(text ? this.indentUnit.repeat(this.depth) + text : "");
    return this;
  }

  lines_(texts: string[]): this {
    texts.forEach((t) => this.line(t));
    return this;
  }

  /** Emits `open`, indents the body, then emits `close`. */
  block(open: string, body: () => void, close = "}"): this {
    this.line(open);
    this.depth++;
    body();
    this.depth--;
    if (close) this.line(close);
    return this;
  }

  /** C++ namespace: body is not indented (Google style). */
  namespace(name: string, body: () => void): this {
    this.line(`namespace ${name} {`);
    body();
    this.line(`}  // namespace ${name}`);
    return this;
  }

  indent(body: () => void): this {
    this.depth++;
    body();
    this.depth--;
    return this;
  }

  raw(text: string): this {
    for (const l of text.replace(/\n$/, "").split("\n")) this.line(l);
    return this;
  }

  toString(): string {
    return this.lines.join("\n").replace(/\n{3,}/g, "\n\n") + "\n";
  }
}

export const pascal = (s: string) =>
  s
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0]!.toUpperCase() + p.slice(1))
    .join("");

export const upper = (s: string) => s.replace(/[^A-Za-z0-9]+/g, "_").toUpperCase();

/** Formats a number as a C++ float literal. */
export const cppFloat = (n: number) => {
  const s = Number.isInteger(n) ? `${n}.0` : String(n);
  return `${s}f`;
};

export const pyFloat = (n: number) => (Number.isInteger(n) ? `${n}.0` : String(n));

export const cppString = (s: string) => JSON.stringify(s);

export const hex2 = (n: number) => `0x${n.toString(16).toUpperCase().padStart(2, "0")}`;

/** Non-cryptographic 64-bit FNV-1a content hash (portable: browser + node). */
export function contentHash(text: string): string {
  let h = 0xcbf29ce484222325n;
  const prime = 0x100000001b3n;
  const bytes = new TextEncoder().encode(text);
  for (const b of bytes) {
    h ^= BigInt(b);
    h = (h * prime) & 0xffffffffffffffffn;
  }
  return h.toString(16).padStart(16, "0");
}

