function emitUrdf(ctx: GenerationContext): string {
  const hw = ctx.ir.hardware;
  const drive = ctx.spec.robot.drive;
  const wheelIds = new Set(drive ? [...drive.leftMotors, ...drive.rightMotors] : []);
  const w = new CodeWriter();
  w.line('<?xml version="1.0"?>');
  w.line("<!-- GENERATED by RoboForge from robot.yaml (component mount poses). -->");
  w.block(`<robot name="${ctx.spec.robot.name}" xmlns:xacro="http://www.ros.org/wiki/xacro">`, () => {
    w.line('<xacro:property name="base_length" value="0.26"/>');
    w.line('<xacro:property name="base_width" value="0.20"/>');
    w.line('<xacro:property name="base_height" value="0.06"/>');
    w.line();
    w.line('<link name="base_footprint"/>');
    w.block('<link name="base_link">', () => {
      w.line('<visual><geometry><box size="${base_length} ${base_width} ${base_height}"/></geometry></visual>');
      w.line('<collision><geometry><box size="${base_length} ${base_width} ${base_height}"/></geometry></collision>');
      w.line('<inertial><mass value="1.5"/><inertia ixx="0.006" ixy="0" ixz="0" iyy="0.009" iyz="0" izz="0.013"/></inertial>');
    }, "</link>");
    w.block('<joint name="base_joint" type="fixed">', () => {
      w.line('<parent link="base_footprint"/><child link="base_link"/>');
      w.line(`<origin xyz="0 0 ${pyFloat(drive?.wheelRadiusM ?? 0.035)}" rpy="0 0 0"/>`);
    }, "</joint>");
    for (const rc of hw.components) {
      const m = rc.instance.mount;
      const isWheel = wheelIds.has(rc.instance.id);
      if (!m && !isWheel && !rc.def.sensor) continue;
      const pose = m ?? { x: 0, y: 0, z: 0, yawDeg: 0 };
      const yaw = (pose.yawDeg * Math.PI) / 180;
      const name = rc.instance.name;
      w.line();
      if (isWheel) {
        const r = typeof rc.instance.config["wheelRadiusM"] === "number" ? (rc.instance.config["wheelRadiusM"] as number) : drive?.wheelRadiusM ?? 0.035;
        w.block(`<link name="${name}_wheel">`, () => {
          w.line(`<visual><origin rpy="1.5708 0 0"/><geometry><cylinder radius="${r}" length="0.025"/></geometry></visual>`);
          w.line(`<collision><origin rpy="1.5708 0 0"/><geometry><cylinder radius="${r}" length="0.025"/></geometry></collision>`);
          w.line('<inertial><mass value="0.08"/><inertia ixx="0.00003" ixy="0" ixz="0" iyy="0.00005" iyz="0" izz="0.00003"/></inertial>');
        }, "</link>");
        w.block(`<joint name="${name}_joint" type="continuous">`, () => {
          w.line(`<parent link="base_link"/><child link="${name}_wheel"/>`);
          w.line(`<origin xyz="${pose.x} ${pose.y} ${pose.z - (drive?.wheelRadiusM ?? 0.035)}" rpy="0 0 0"/>`);
          w.line('<axis xyz="0 1 0"/>');
        }, "</joint>");
      } else {
        const box = rc.def.geometry?.box ?? [0.02, 0.02, 0.01];
        w.block(`<link name="${name}_link">`, () => {
          w.line(`<visual><geometry><box size="${box.join(" ")}"/></geometry></visual>`);
        }, "</link>");
        w.block(`<joint name="${name}_joint" type="fixed">`, () => {
          w.line(`<parent link="base_link"/><child link="${name}_link"/>`);
          w.line(`<origin xyz="${pose.x} ${pose.y} ${pose.z}" rpy="0 0 ${Number(yaw.toFixed(6))}"/>`);
        }, "</joint>");
      }
    }
  }, "</robot>");
  return w.toString();
}

