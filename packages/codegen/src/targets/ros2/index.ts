function emitTopicHal(): string {
  return `${GENERATED_BANNER_PY("Topic-backed implementations of the behavior HAL")}
"""Each device is exposed as ROS 2 topics. The hardware side (firmware bridge, simulator or a
driver node) publishes sensor topics and subscribes to motor command topics.

  motors/<name>/command   std_msgs/Float32   normalized speed [-1, 1]
  servos/<name>/command   std_msgs/Float32   angle in degrees
  sensors/<name>/range    sensor_msgs/Range  distance sensors
  sensors/<name>/imu      sensor_msgs/Imu    IMUs
  sensors/<name>/active   std_msgs/Bool      switches / e-stop
  scan                    sensor_msgs/LaserScan (LiDAR)
  outputs/enable          std_msgs/Bool      motor power-stage enable
"""
from __future__ import annotations

import math
import time
from typing import Optional

from rclpy.node import Node
from sensor_msgs.msg import Imu as ImuMsg
from sensor_msgs.msg import LaserScan, Range
from std_msgs.msg import Bool, Float32

from .behavior import ImuSample


class _Fresh:
    """Holds the latest value and reports None once it is older than the timeout."""

    def __init__(self, timeout_s: float) -> None:
        self.timeout_s = timeout_s
        self.value = None
        self.stamp = 0.0

    def set(self, value) -> None:
        self.value = value
        self.stamp = time.monotonic()

    def get(self):
        if self.value is None or time.monotonic() - self.stamp > self.timeout_s:
            return None
        return self.value


class TopicMotor:
    def __init__(self, node: Node, name: str) -> None:
        self._pub = node.create_publisher(Float32, f"motors/{name}/command", 10)
        self._speed = 0.0

    def set_speed(self, speed: float) -> None:
        self._speed = max(-1.0, min(1.0, float(speed)))
        self._pub.publish(Float32(data=self._speed))

    def stop(self) -> None:
        self.set_speed(0.0)

    def speed(self) -> float:
        return self._speed


class TopicServo:
    def __init__(self, node: Node, name: str) -> None:
        self._pub = node.create_publisher(Float32, f"servos/{name}/command", 10)

    def set_angle_deg(self, angle_deg: float) -> None:
        self._pub.publish(Float32(data=float(angle_deg)))


class TopicDistanceSensor:
    def __init__(self, node: Node, name: str, timeout_s: float) -> None:
        self._v = _Fresh(timeout_s)
        node.create_subscription(Range, f"sensors/{name}/range", self._on_msg, 10)

    def _on_msg(self, msg: Range) -> None:
        r = msg.range
        if math.isinf(r) and r > 0:
            r = msg.max_range
        if math.isfinite(r):
            self._v.set(float(r))

    def read_distance_m(self) -> Optional[float]:
        return self._v.get()


class TopicImu:
    def __init__(self, node: Node, name: str, timeout_s: float) -> None:
        self._v = _Fresh(timeout_s)
        node.create_subscription(ImuMsg, f"sensors/{name}/imu", self._on_msg, 10)

    def _on_msg(self, msg: ImuMsg) -> None:
        q = msg.orientation
        yaw = math.degrees(math.atan2(2.0 * (q.w * q.z + q.x * q.y), 1.0 - 2.0 * (q.y * q.y + q.z * q.z)))
        pitch = math.degrees(math.asin(max(-1.0, min(1.0, 2.0 * (q.w * q.y - q.z * q.x)))))
        roll = math.degrees(math.atan2(2.0 * (q.w * q.x + q.y * q.z), 1.0 - 2.0 * (q.x * q.x + q.y * q.y)))
        self._v.set(ImuSample(
            yaw_deg=yaw, pitch_deg=pitch, roll_deg=roll,
            gyro_z_dps=math.degrees(msg.angular_velocity.z),
            accel_x=msg.linear_acceleration.x, accel_y=msg.linear_acceleration.y, accel_z=msg.linear_acceleration.z,
        ))

    def read(self) -> Optional[ImuSample]:
        return self._v.get()


class TopicSwitch:
    """Fails safe: a missing or stale message counts as ACTIVE for safety inputs."""

    def __init__(self, node: Node, name: str, timeout_s: float, fail_active: bool) -> None:
        self._v = _Fresh(timeout_s)
        self._fail_active = fail_active
        node.create_subscription(Bool, f"sensors/{name}/active", lambda m: self._v.set(bool(m.data)), 10)

    def is_active(self) -> bool:
        v = self._v.get()
        return self._fail_active if v is None else v


class TopicLidar:
    def __init__(self, node: Node, topic: str, timeout_s: float, front_half_angle_deg: float = 15.0) -> None:
        self._v = _Fresh(timeout_s)
        self._half = math.radians(front_half_angle_deg)
        node.create_subscription(LaserScan, topic, self._on_msg, 10)

    def _on_msg(self, msg: LaserScan) -> None:
        valid = []
        front = []
        for i, r in enumerate(msg.ranges):
            if not (msg.range_min <= r <= msg.range_max):
                continue
            valid.append(r)
            a = msg.angle_min + i * msg.angle_increment
            a = math.atan2(math.sin(a), math.cos(a))
            if abs(a) <= self._half:
                front.append(r)
        self._v.set({
            "min_distance_m": min(valid) if valid else msg.range_max,
            "front_distance_m": min(front) if front else msg.range_max,
        })

    def read_channel(self, channel: str) -> Optional[float]:
        v = self._v.get()
        return None if v is None else v.get(channel)


class TopicOutputEnable:
    def __init__(self, node: Node) -> None:
        self._pub = node.create_publisher(Bool, "outputs/enable", 10)

    def set_enabled(self, enabled: bool) -> None:
        self._pub.publish(Bool(data=bool(enabled)))


class NodeLogger:
    def __init__(self, node: Node) -> None:
        self._log = node.get_logger()

    def info(self, message: str) -> None:
        self._log.info(message)

    def warn(self, message: str) -> None:
        self._log.warning(message)
`;
}

function emitNode(ctx: GenerationContext, devices: PyDevice[]): string {
  const drive = ctx.spec.robot.drive;
  const nm = (id: string) => ctx.ir.hardware.byId.get(id)?.instance.name ?? id;
  const estops = new Set(ctx.ir.behavior.estopComponentIds.map(nm));
  const ctor = (d: PyDevice) => {
    switch (d.hal) {
      case "motor": return `TopicMotor(self, "${d.name}")`;
      case "servo": return `TopicServo(self, "${d.name}")`;
      case "distance": return `TopicDistanceSensor(self, "${d.name}", timeout)`;
      case "imu": return `TopicImu(self, "${d.name}", timeout)`;
      case "switch": return `TopicSwitch(self, "${d.name}", timeout, fail_active=${estops.has(d.name) ? "True" : "False"})`;
      case "lidar": return `TopicLidar(self, "scan", timeout)`;
    }
  };
  const halClass: Record<PyDevice["hal"], string> = {
    motor: "TopicMotor",
    servo: "TopicServo",
    distance: "TopicDistanceSensor",
    imu: "TopicImu",
    switch: "TopicSwitch",
    lidar: "TopicLidar",
  };
  const halImports = [...new Set(["NodeLogger", "TopicOutputEnable", ...devices.map((d) => halClass[d.hal])])].sort();
  return `${GENERATED_BANNER_PY("ROS 2 node running the robot behavior")}
from __future__ import annotations

import time

import rclpy
from geometry_msgs.msg import Twist
from rclpy.node import Node
from std_msgs.msg import Bool, String

from . import user_functions
from .behavior import Behavior, Robot
from .topic_hal import (
${halImports.map((c) => `    ${c},`).join("\n")}
)


class BehaviorNode(Node):
    def __init__(self) -> None:
        super().__init__("${ctx.spec.robot.name}_behavior")
        self.declare_parameter("tick_rate_hz", 100.0)
        self.declare_parameter("sensor_timeout_s", 0.5)
${drive ? `        self.declare_parameter("max_speed_mps", ${pyFloat(drive.maxSpeedMps)})
        self.declare_parameter("track_width_m", ${pyFloat(drive.trackWidthM)})
` : ""}        timeout = float(self.get_parameter("sensor_timeout_s").value)

        self.robot = Robot(
${devices.map((d) => `            ${d.name}=${ctor(d)},`).join("\n")}
            outputs=TopicOutputEnable(self),
            log=NodeLogger(self),
        )
        self.behavior = Behavior(self.robot, user=user_functions)
        self._t0 = time.monotonic()
        self._state_pub = self.create_publisher(String, "behavior/state", 10)
        self._estop_pub = self.create_publisher(Bool, "behavior/estop_latched", 10)
${drive ? `        self._cmd_vel_pub = self.create_publisher(Twist, "cmd_vel", 10)
` : ""}        self.behavior.begin(self._now_ms())
        period = 1.0 / float(self.get_parameter("tick_rate_hz").value)
        self.create_timer(period, self._tick)
        self.get_logger().info("behavior started")

    def _now_ms(self) -> int:
        return int((time.monotonic() - self._t0) * 1000.0)

    def _tick(self) -> None:
        self.behavior.tick(self._now_ms())
        self._state_pub.publish(String(data=self.behavior.state.value))
        self._estop_pub.publish(Bool(data=self.behavior.estop_latched))
${drive ? `        self._publish_cmd_vel()

    def _publish_cmd_vel(self) -> None:
        """Differential-drive view of the per-motor commands, for navigation/odometry tooling."""
        left = [${drive.leftMotors.map((id) => `self.robot.${nm(id)}.speed()`).join(", ")}]
        right = [${drive.rightMotors.map((id) => `self.robot.${nm(id)}.speed()`).join(", ")}]
        vmax = float(self.get_parameter("max_speed_mps").value)
        track = float(self.get_parameter("track_width_m").value)
        vl = sum(left) / len(left) * vmax
        vr = sum(right) / len(right) * vmax
        msg = Twist()
        msg.linear.x = (vl + vr) / 2.0
        msg.angular.z = (vr - vl) / track
        self._cmd_vel_pub.publish(msg)
` : ""}

def main(args=None) -> None:
    rclpy.init(args=args)
    node = BehaviorNode()
    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        pass
    finally:
        node.behavior.stop_all_motors()
        node.destroy_node()
        rclpy.try_shutdown()


if __name__ == "__main__":
    main()
`.replace(/\n{3,}def main/, "\n\n\ndef main");
}

