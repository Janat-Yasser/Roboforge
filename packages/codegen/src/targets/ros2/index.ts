function emitParams(ctx: GenerationContext, devices: PyDevice[]): string {
  const drive = ctx.spec.robot.drive;
  return `${GENERATED_BANNER_HASH("ROS 2 parameters")}
${ctx.spec.robot.name}_behavior:
  ros__parameters:
    tick_rate_hz: 100.0
    sensor_timeout_s: 0.5
${drive ? `    max_speed_mps: ${pyFloat(drive.maxSpeedMps)}\n    track_width_m: ${pyFloat(drive.trackWidthM)}\n` : ""}
# Device topics (relative to the node namespace):
${devices.map((d) => `#   ${d.name.padEnd(16)} ${d.hal === "motor" ? `motors/${d.name}/command` : d.hal === "servo" ? `servos/${d.name}/command` : d.hal === "distance" ? `sensors/${d.name}/range` : d.hal === "imu" ? `sensors/${d.name}/imu` : d.hal === "switch" ? `sensors/${d.name}/active` : "scan"}`).join("\n")}
`;
}

function emitBringup(ctx: GenerationContext, pk: { description: string; bringup: string; control: string }): string {
  const robot = ctx.spec.robot.name;
  const lidar = ctx.ir.hardware.components.find((c) => c.def.sensor?.kind === "lidar");
  return `${GENERATED_BANNER_PY("Robot bringup")}
import os

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument
from launch.conditions import IfCondition
from launch.substitutions import Command, LaunchConfiguration
from launch_ros.actions import Node
from launch_ros.parameter_descriptions import ParameterValue


def generate_launch_description():
    description_share = get_package_share_directory("${pk.description}")
    bringup_share = get_package_share_directory("${pk.bringup}")
    xacro_file = os.path.join(description_share, "urdf", "${robot}.urdf.xacro")
    params_file = os.path.join(bringup_share, "config", "robot_params.yaml")
    robot_description = ParameterValue(Command(["xacro ", xacro_file]), value_type=str)

    return LaunchDescription([
        DeclareLaunchArgument("namespace", default_value="${robot}"),
${lidar ? `        DeclareLaunchArgument("start_lidar_driver", default_value="false",
                              description="Start the vendor LiDAR driver (rplidar_ros must be installed)"),
` : ""}        Node(
            package="robot_state_publisher",
            executable="robot_state_publisher",
            namespace=LaunchConfiguration("namespace"),
            parameters=[{"robot_description": robot_description}],
        ),
        Node(
            package="${pk.control}",
            executable="behavior_node",
            namespace=LaunchConfiguration("namespace"),
            parameters=[params_file],
            output="screen",
        ),
${lidar ? `        Node(
            package="rplidar_ros",
            executable="rplidar_node",
            namespace=LaunchConfiguration("namespace"),
            parameters=[{"frame_id": "${lidar.instance.name}_link", "serial_baudrate": 115200}],
            condition=IfCondition(LaunchConfiguration("start_lidar_driver")),
        ),
` : ""}    ])
`;
}
